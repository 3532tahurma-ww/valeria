# Builds js/data/portraits.js from chars/ and js/data/music.js from Music/ (run: portreleri-guncelle.bat)
$root = Split-Path -Parent $PSScriptRoot
$utf8 = New-Object Text.UTF8Encoding $false

$files = Get-ChildItem (Join-Path $root 'chars') -File |
  Where-Object { $_.Extension -match '^\.(jpe?g|png|webp|gif)$' } | Sort-Object Name
$items = $files | ForEach-Object { "  'chars/" + $_.Name.Replace("'", "\'") + "'" }
$js = "/* AUTO-GENERATED by tools/build-portraits.ps1 - do not edit. Portraits in chars/ */`n" +
  "(self.Valeria = self.Valeria || {}).PORTRAITS = [`n" + ($items -join ",`n") + "`n];`n"
[IO.File]::WriteAllText((Join-Path $root 'js\data\portraits.js'), $js, $utf8)
Write-Host "$($files.Count) portraits -> js/data/portraits.js"

$tracks = @()
if (Test-Path (Join-Path $root 'Music')) {
  $tracks = Get-ChildItem (Join-Path $root 'Music') -File | Where-Object { $_.Extension -match '^\.(mp3|ogg|m4a|wav)$' } | Sort-Object Name
}
$items = $tracks | ForEach-Object { "  'Music/" + $_.Name.Replace("'", "\'") + "'" }
$js = "/* AUTO-GENERATED by tools/build-portraits.ps1 - do not edit. Background music in Music/ (played in order, looping) */`n" +
  "(self.Valeria = self.Valeria || {}).MUSIC = [`n" + ($items -join ",`n") + "`n];`n"
[IO.File]::WriteAllText((Join-Path $root 'js\data\music.js'), $js, $utf8)
Write-Host "$($tracks.Count) tracks -> js/data/music.js"
